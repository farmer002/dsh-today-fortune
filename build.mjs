/*
 * Builds lib/client.js: one self-contained browser bundle.
 *
 * The bundle is a plain classic script that registers a lazy factory with
 * window.__ModuleLoader__. Bundled inside the factory closure:
 *   - vendor/lunar.js  (lunar-javascript, UMD, wrapped into a local module)
 *   - src/*.js         (authoring modules sharing one `F` namespace)
 *   - assets/*.svg     (inlined as strings; no runtime fetches)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, p), 'utf8');

const SRC_ORDER = [
  'src/util.js',
  'src/almanac.js',
  'src/luckyDays.js',
  'src/copy.js',
  'src/mapper.js',
  'src/easterEgg.js',
  'src/anim.js',
  'src/store.js',
  'src/share.js',
  'src/view.js',
  'src/app.js',
];

const ASSETS = {
  orbTemple: 'assets/orb-temple.svg',
  censer1: 'assets/censer-t1.svg',
  censer2: 'assets/censer-t2.svg',
  censer3: 'assets/censer-t3.svg',
  slip: 'assets/slip.svg',
  work: 'assets/icons/work.svg',
  life: 'assets/icons/life.svg',
  study: 'assets/icons/study.svg',
  trophy: 'assets/icons/trophy.svg',
};

const pkg = JSON.parse(read('package.json'));
const id = pkg.name;

for (const file of SRC_ORDER) {
  if (!existsSync(join(root, file))) throw new Error('missing source module: ' + file);
}

const artEntries = Object.entries(ASSETS)
  .map(([name, path]) => `    ${name}: ${JSON.stringify(read(path))},`)
  .join('\n');

const modules = SRC_ORDER.map((file) => {
  const body = read(file).trimEnd();
  return `      /* ---- ${file} ---- */\n${body}\n`;
}).join('\n');

const vendor = read('vendor/lunar.js').trimEnd();

const out = `/*! dsh-today-fortune ${pkg.version} — generated by build.mjs, do not edit. */
/* Bundled dependency: lunar-javascript (MIT), see vendor/LICENSE-lunar-javascript. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory(require) {
    var React = require('react');
    var h = React.createElement;

    /* lunar-javascript UMD entry, evaluated as a local CommonJS module. */
    var Lunar = (function () {
      var module = { exports: {} };
      var exports = module.exports;
${vendor}
      return module.exports;
    }).call(globalThis);

    var F = (function () {
      var F = {
        React: React,
        h: h,
        Lunar: Lunar,
        art: {
${artEntries}
        },
      };

${modules}
      return F;
    })();

    var App = F.app.App;

    return {
      inject: ['slots'],
      apply: function (ctx) {
        ctx.slots.inject('shell.overlay', function () {
          return ctx.slots.register(
            { name: 'shell.overlay', id: 'dsh-today-fortune-orb', order: 60 },
            App
          );
        });
      },
    };
  },
});
`;

mkdirSync(join(root, 'lib'), { recursive: true });
writeFileSync(join(root, 'lib/client.js'), out, 'utf8');
console.log('lib/client.js written:', out.length, 'bytes');
